"""
KrishiMitra AI -- Live Ollama Integration Test
scripts/test_live_ollama.py
"""

import sys
import os
import time
import asyncio
from unittest.mock import patch

ROOT_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT_DIR)

from backend.app.core.config import settings
from backend.app.core.llm_provider import llm_provider
from backend.app.services.rag_pipeline import rag_pipeline
from backend.app.api.chat import process_chat_intent


async def run_live_test():
    print("=" * 70)
    print("KrishiMitra Live Ollama + RAG Integration Verification")
    print("=" * 70)

    print(f"Provider in settings:     {settings.LLM_PROVIDER}")
    print(f"Provider in llm_provider: {llm_provider.provider}")
    print(f"Ollama Base URL:          {settings.OLLAMA_BASE_URL}")
    print(f"Ollama Model:             {settings.OLLAMA_MODEL}")
    print(f"RAG LLM Mode:             {settings.RAG_LLM_MODE}")
    print(f"RAG Index Documents:      {len(rag_pipeline.documents)}")

    # Verify connection to Ollama
    import httpx
    try:
        r = httpx.get(f"{settings.OLLAMA_BASE_URL}/api/tags", timeout=5.0)
        models = [m["name"] for m in r.json().get("models", [])]
        print(f"Ollama online:            YES (models installed: {models})")
        assert any(settings.OLLAMA_MODEL in m for m in models), f"Model {settings.OLLAMA_MODEL} not found in {models}"
    except Exception as e:
        print(f"Ollama online:            NO ({e})")
        sys.exit(1)

    print("\n--- Running Agricultural Question through RAG + Ollama ---")
    query = "What are the optimal soil pH and water requirements for Cotton in Kharif season in Kurnool?"
    print(f"Farmer Query: '{query}'")

    with patch("backend.app.api.chat.recommender.recommend") as mock_rf:
        t0 = time.time()
        answer, sources, rec_data, comp_data, simple_s, det_a, struct_r, conf, lang, intent = await process_chat_intent(
            message=query,
            language="en",
            session_id="live_ollama_eval",
            req_location=None,
            req_soil_type="Black Soil",
            req_farm_profile=None,
            detail_level="simple"
        )
        latency_ms = int((time.time() - t0) * 1000)

        # Assertions
        assert not mock_rf.called, "Random Forest recommender.recommend was called when it should be bypassed!"
        assert rec_data is None, "rec_data should be None in RAG_LLM_MODE"
        assert len(sources) > 0, "No sources returned!"
        assert len(answer) > 20, "Answer is suspiciously short!"
        assert not answer.startswith("Error communicating with Ollama"), f"Ollama failed with error: {answer}"
        assert "<think>" not in answer, "Thinking tags leaked into answer!"

        print("\n--- Verification Checkpoints ---")
        print(f"[x] Random Forest Bypassed:   recommender.recommend called = {mock_rf.called}")
        print(f"[x] Response Latency:         {latency_ms} ms")
        print(f"[x] Confidence Level:         {conf}")
        print(f"[x] Intent Classification:    {intent}")
        print(f"[x] Sources Returned:         {len(sources)}")
        print("\nRetrieved Source Provenance:")
        for idx, s in enumerate(sources, 1):
            print(f"  {idx}. [{s.get('name')}] {s.get('title')}")
            print(f"     Year: {s.get('publication_year')} | Score: {s.get('score')} | Used: {s.get('used')}")

        print("\n--- Actual Model Response (Generated by Qwen3.5:9b via Ollama) ---")
        print(answer)
        print("\n" + "=" * 70)
        print(" LIVE OLLAMA + RAG INTEGRATION TEST PASSED!")
        print("=" * 70)


if __name__ == "__main__":
    asyncio.run(run_live_test())
